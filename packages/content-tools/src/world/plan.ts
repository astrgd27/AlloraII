/**
 * The world plan: how many places each realm should have in the finished game.
 * The owner's target is about 2,200 places (CLAUDE.md), split by land and then
 * evenly between the realms of a land. Polygoetia is split by island.
 */

/** Land id (the `world` field of a region; the Seven have none) → places in the finished game. */
export const LAND_TARGETS: Record<string, number> = {
  seven: 560,
  gallar: 480,
  qoul: 480,
  east: 420,
  polygoetia: 260,
};

/** The share of a realm's places that are of each kind (design bible, A world of small places). */
export const KIND_SHARES: Record<string, number> = {
  city: 0.05,
  town: 0.15,
  village: 0.35,
  site: 0.35,
  wild: 0.1,
};

export interface PlanUnit {
  /** A canon region, or a Polygoetian island. */
  id: string;
  name: string;
  land: string;
  /** Canon places already there. */
  canon: number;
}

export interface PlanRow extends PlanUnit {
  target: number;
  kinds: Record<string, number>;
}

/** Splits a whole number into parts by share, so the parts sum exactly (largest remainder). */
export function splitByShare(total: number, shares: number[]): number[] {
  const sum = shares.reduce((a, b) => a + b, 0);
  const exact = shares.map((s) => (total * s) / sum);
  const parts = exact.map(Math.floor);
  let left = total - parts.reduce((a, b) => a + b, 0);
  const order = exact
    .map((x, i) => [x - Math.floor(x), i] as const)
    .sort((a, b) => b[0] - a[0] || a[1] - b[1]);
  for (const [, i] of order) {
    if (left-- <= 0) break;
    parts[i] = (parts[i] ?? 0) + 1;
  }
  return parts;
}

export function buildPlan(units: PlanUnit[]): PlanRow[] {
  const rows: PlanRow[] = [];
  for (const [land, total] of Object.entries(LAND_TARGETS)) {
    const inLand = units.filter((u) => u.land === land);
    if (inLand.length === 0) throw new Error(`No regions found for land "${land}"`);
    const targets = splitByShare(
      total,
      inLand.map(() => 1),
    );
    inLand.forEach((unit, i) => {
      const target = targets[i] ?? 0;
      if (target < unit.canon) {
        throw new Error(`${unit.id}: target ${target} is below its ${unit.canon} canon places`);
      }
      const kindNames = Object.keys(KIND_SHARES);
      const counts = splitByShare(target, Object.values(KIND_SHARES));
      rows.push({
        ...unit,
        target,
        kinds: Object.fromEntries(kindNames.map((k, j) => [k, counts[j] ?? 0])),
      });
    });
  }
  return rows;
}

export interface Progress {
  id: string;
  name: string;
  land: string;
  built: number;
  target: number;
}

/** Places built (canon and new) against target, per unit. `builtBy` maps unit id → places there. */
export function progress(plan: PlanRow[], builtBy: Map<string, number>): Progress[] {
  return plan.map((row) => ({
    id: row.id,
    name: row.name,
    land: row.land,
    built: builtBy.get(row.id) ?? 0,
    target: row.target,
  }));
}

export function renderProgress(rows: Progress[]): string {
  const lines = [
    '# World plan: places built against target',
    '',
    'Generated by `pnpm world:plan`. Do not edit by hand.',
    '',
  ];
  const total = (list: Progress[], key: 'built' | 'target') => list.reduce((n, r) => n + r[key], 0);
  lines.push(`**Whole world: ${total(rows, 'built')} of ${total(rows, 'target')} places.**`, '');
  for (const land of Object.keys(LAND_TARGETS)) {
    const list = rows.filter((r) => r.land === land);
    lines.push(
      `## ${land} (${total(list, 'built')} of ${total(list, 'target')})`,
      '',
      '| Realm | Built | Target |',
      '| --- | ---: | ---: |',
    );
    for (const r of list) lines.push(`| ${r.name} | ${r.built} | ${r.target} |`);
    lines.push('');
  }
  return lines.join('\n');
}
