/**
 * `pnpm world:plan`: writes the world plan (content/plan/world-plan.yaml) and
 * the count of places built against it (docs/world-plan.md).
 * `--check` fails if either file is out of date.
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse, stringify } from 'yaml';
import { loadContent } from '../lint/load';
import { buildPlan, progress, renderProgress, type PlanUnit } from './plan';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../../../..');
const PLAN = 'content/plan/world-plan.yaml';
const REPORT = 'docs/world-plan.md';
const HEADER =
  '# Generated by `pnpm world:plan`. Do not edit by hand.\n' +
  '# Places each realm should have in the finished game. The targets are set in\n' +
  '# packages/content-tools/src/world/plan.ts.\n';

type Raw = Record<string, unknown>;
const readYaml = async (path: string): Promise<Raw[]> =>
  parse(await readFile(join(ROOT, path), 'utf8')) as Raw[];

async function main(): Promise<void> {
  const check = process.argv.includes('--check');
  const regions = await readYaml('content/canon/allora1/regions.yaml');
  const islands = await readYaml('content/canon/polygoetia/places.yaml');
  const content = await loadContent(ROOT);
  const places = content.filter((c) => c.entry.kind === 'place');

  // A place counts towards its region; in Polygoetia, an island counts as itself
  // and a new place there counts towards the island it names in `island`.
  const builtBy = new Map<string, number>();
  const count = (id: unknown) => {
    if (typeof id === 'string') builtBy.set(id, (builtBy.get(id) ?? 0) + 1);
  };
  for (const { entry } of places) {
    if (entry.origin === 'polygoetia') count(entry.id);
    else count(entry.island ?? entry.region);
  }

  const canonIn = (id: string) =>
    places.filter((p) => p.canon && (p.entry.region === id || p.entry.id === id)).length;
  const units: PlanUnit[] = [
    ...regions.map((r) => ({
      id: String(r.id),
      name: String(r.name),
      land: typeof r.world === 'string' ? r.world : 'seven',
      canon: canonIn(String(r.id)),
    })),
    ...islands.map((p) => ({
      id: String(p.id),
      name: String(p.name),
      land: 'polygoetia',
      canon: 1,
    })),
  ];

  const plan = buildPlan(units);
  const files: [string, string][] = [
    [
      PLAN,
      HEADER +
        stringify(
          plan.map(({ id, name, land, target, kinds }) => ({ id, name, land, target, kinds })),
        ),
    ],
    [REPORT, renderProgress(progress(plan, builtBy))],
  ];

  if (check) {
    const stale: string[] = [];
    for (const [path, text] of files) {
      if ((await readFile(join(ROOT, path), 'utf8').catch(() => undefined)) !== text)
        stale.push(path);
    }
    if (stale.length > 0) {
      console.error(`Out of date: ${stale.join(', ')}. Run \`pnpm world:plan\`.`);
      process.exit(1);
    }
    console.log('The world plan is up to date.');
    return;
  }
  for (const [path, text] of files) {
    await mkdir(dirname(join(ROOT, path)), { recursive: true });
    await writeFile(join(ROOT, path), text);
  }
  const rows = progress(plan, builtBy);
  console.log(
    `Wrote the world plan: ${rows.reduce((n, r) => n + r.built, 0)} of ${rows.reduce((n, r) => n + r.target, 0)} places built.`,
  );
}

main().catch((e: unknown) => {
  console.error(e);
  process.exit(1);
});
