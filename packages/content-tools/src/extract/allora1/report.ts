/** Writes content/canon/allora1/REPORT.md. Nothing in it depends on the time or machine. */
import type { Dropped } from './transform';

export interface KindCount {
  file: string;
  kind: string;
  table: string;
  about: string;
  /** Rows of the game's own table that belong to this kind. */
  gameCount: number;
  /** Entries written to the YAML file. */
  written: number;
}

export interface ReportInput {
  sourceFile: string;
  sourceSha256: string;
  counts: KindCount[];
  /** Total rows of tables that are split across files (ITEMS). */
  tableTotals: Record<string, number>;
  dropped: Dropped[];
  unreadable: { table: string; error: string }[];
  idMismatches: { kind: string; ids: string[] }[];
  orphanSubs: string[];
  pageErrors: string | undefined;
  notExtracted: string[];
}

const row = (cells: (string | number)[]) => `| ${cells.join(' | ')} |`;

export function renderReport(r: ReportInput): string {
  const lines: string[] = [];
  lines.push('# Allora I extraction report');
  lines.push('');
  lines.push('Generated by `pnpm extract`. Do not edit by hand.');
  lines.push('');
  lines.push(`- Source: \`${r.sourceFile}\``);
  lines.push(`- Source SHA-256: \`${r.sourceSha256}\``);
  lines.push('- Every entry keeps its Allora I id and carries `origin: allora1` and a `kind`.');
  lines.push(
    "- Item quality variants keep the game's own keys, `<item>#<quality>`, and name their `base` item.",
  );
  lines.push(
    '- Sub-places are nested under their place. Refer to one as `<place id>/<sub-place id>`.',
  );
  lines.push('');
  lines.push('## Counts by kind');
  lines.push('');
  lines.push(row(['File', 'Kind', 'Game table', 'In the game', 'Written', 'Match', 'What']));
  lines.push(row(['---', '---', '---', '---:', '---:', '---', '---']));
  for (const c of r.counts) {
    lines.push(
      row([
        `\`${c.file}.yaml\``,
        c.kind,
        `\`${c.table}\``,
        c.gameCount,
        c.written,
        c.gameCount === c.written ? 'yes' : '**no**',
        c.about,
      ]),
    );
  }
  const totalWritten = r.counts.reduce((n, c) => n + c.written, 0);
  lines.push('');
  lines.push(`Total entries written: ${totalWritten}.`);
  for (const [table, total] of Object.entries(r.tableTotals)) {
    const parts = r.counts.filter((c) => c.table === table);
    if (parts.length < 2) continue;
    const sum = parts.reduce((n, c) => n + c.written, 0);
    lines.push(
      `\`${table}\` has ${total} rows in the game, split as ${parts
        .map((p) => `${p.written} ${p.kind}`)
        .join(' + ')} = ${sum}${sum === total ? '' : ' (**does not add up**)'}.`,
    );
  }
  lines.push('');
  lines.push('## Could not be read');
  lines.push('');
  const problems: string[] = [];
  for (const u of r.unreadable) problems.push(`- Table \`${u.table}\`: ${u.error}`);
  if (r.pageErrors) problems.push(`- The page reported errors while loading: ${r.pageErrors}`);
  for (const m of r.idMismatches) {
    problems.push(`- ${m.kind}: entries whose own id differs from their key: ${m.ids.join(', ')}`);
  }
  if (r.orphanSubs.length > 0) {
    problems.push(`- Sub-places listed for places that do not exist: ${r.orphanSubs.join(', ')}`);
  }
  lines.push(problems.length > 0 ? problems.join('\n') : 'Nothing: every table was read in full.');
  lines.push('');
  lines.push('## Left out on purpose');
  lines.push('');
  lines.push(
    "Some fields in the game hold code (conditions and effects written as functions), not data, and a few hold a number that is not a number (NaN). YAML cannot hold either, so they are left out and counted here. The code's behaviour is a system question for Allora II, not canon text.",
  );
  lines.push('');
  if (r.dropped.length === 0) {
    lines.push('None.');
  } else {
    lines.push(row(['Kind', 'Field', 'Why', 'Count', 'For example']));
    lines.push(row(['---', '---', '---', '---:', '---']));
    for (const d of r.dropped) {
      const ex = d.examples.map((e) => `\`${e}\``).join(', ');
      lines.push(row([d.kind, `\`${d.path}\``, d.reason, d.count, ex]));
    }
  }
  lines.push('');
  lines.push('## Tables not extracted yet');
  lines.push('');
  lines.push(
    'The game holds more tables than the kinds above (quests, events, bestiary, romance, decor and many more). These are not part of the Phase 0 extraction and are read straight from `canon/allora-1.html` when needed:',
  );
  lines.push('');
  lines.push(r.notExtracted.map((t) => `\`${t}\``).join(', '));
  lines.push('');
  return lines.join('\n');
}
