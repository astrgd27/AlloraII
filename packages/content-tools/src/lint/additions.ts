/** Writes docs/lore/additions.md: every addition and its roots, land by land. */
import type { Entry, Loaded } from './types';

const LAND_NAMES: Record<string, string> = {
  seven: 'The Seven',
  gallar: 'Gallar',
  qoul: 'Qoul',
  east: 'Thoolma',
  polygoetia: 'Polygoetia',
};
const LAND_ORDER = ['The Seven', 'Gallar', 'Qoul', 'Thoolma', 'Polygoetia', 'Unplaced'];

/** Finds the land of an entry through its region, its place, or its roots. */
export function landOf(entry: Entry, byId: Map<string, Entry>, seen = new Set<string>()): string {
  if (seen.has(entry.id)) return 'Unplaced';
  seen.add(entry.id);
  if (entry.kind === 'region') {
    // Allora I leaves `world` out for regions of the Seven.
    return LAND_NAMES[typeof entry.world === 'string' ? entry.world : 'seven'] ?? 'Unplaced';
  }
  if (typeof entry.world === 'string' && LAND_NAMES[entry.world]) return LAND_NAMES[entry.world]!;
  const next = [entry.region, entry.place, entry.home, entry.seat, ...(entry.roots ?? [])];
  for (const id of next) {
    if (typeof id !== 'string') continue;
    const target = byId.get(id.split('/')[0] ?? id);
    if (!target) continue;
    const land = landOf(target, byId, seen);
    if (land !== 'Unplaced') return land;
  }
  return 'Unplaced';
}

export function renderAdditions(all: Loaded[]): string {
  const byId = new Map<string, Entry>();
  // Regions and places first, so an id shared with another kind resolves to the place.
  for (const { entry } of all) if (!byId.has(entry.id)) byId.set(entry.id, entry);
  for (const { entry } of all) {
    if (entry.kind === 'region' || entry.kind === 'place') byId.set(entry.id, entry);
  }
  const additions = all.filter((l) => !l.canon);
  const lines = [
    '# Additions ledger',
    '',
    'Generated by `pnpm lint:content`. Do not edit by hand.',
    '',
    'Everything Allora II has added to the world, with the canon it grows from.',
    '',
    `Total additions: ${additions.length}.`,
    '',
  ];
  const groups = new Map<string, Loaded[]>();
  for (const a of additions) {
    const land = landOf(a.entry, byId);
    groups.set(land, [...(groups.get(land) ?? []), a]);
  }
  for (const land of LAND_ORDER) {
    const list = groups.get(land);
    if (!list) continue;
    lines.push(
      `## ${land} (${list.length})`,
      '',
      '| Kind | Name | Id | Roots | File |',
      '| --- | --- | --- | --- | --- |',
    );
    const sorted = [...list].sort(
      (a, b) =>
        (a.entry.kind ?? '').localeCompare(b.entry.kind ?? '') ||
        a.entry.id.localeCompare(b.entry.id),
    );
    for (const { entry, file } of sorted) {
      const roots = (entry.roots ?? []).map((r) => `\`${r}\``).join(', ');
      lines.push(
        `| ${entry.kind ?? ''} | ${entry.name ?? ''} | \`${entry.id}\` | ${roots} | \`${file}\` |`,
      );
    }
    lines.push('');
  }
  return lines.join('\n');
}
